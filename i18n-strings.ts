/**
 * Initialise i18n with the strings for the user's preferred locale.
 * Falls back to English (loaded first) for any missing keys.
 *
 * Call this once from the plugin's onload() — see main.ts.
 */
export function initI18n(locale: string = 'en'): void {
    // Always load English first so missing keys in other locales fall back.
    registerStrings(EN);
    if (locale === 'ru') {
        registerStrings(RU);
    }
    // Other locales can be added here — they will inherit from EN for any
    // keys they don't override.
}
